"""Publish portable launchers around hooks installed by git-hooks.nix."""

import hashlib
import os
from pathlib import Path
import platform
import shlex
import subprocess
import sys
import tempfile


MARKER = "# idr-git-hook-launcher-v1\n"
PAYLOAD = "# idr-git-hook-payload: "


def git(*args):
    return subprocess.check_output([sys.argv[1], *args], text=True).strip()


def publish(path, content):
    if path.is_file() and not path.is_symlink() and path.read_text() == content:
        return
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as f:
        temporary = Path(f.name)
        try:
            f.write(content)
            f.flush()
            os.fchmod(f.fileno(), 0o755)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def managed_payload(hook, content):
    if MARKER not in content:
        return None
    for line in content.splitlines():
        if line.startswith(PAYLOAD):
            name = line.removeprefix(PAYLOAD)
            if "/" not in name and name.startswith(hook.name + ".idr-"):
                return hook.parent / name
    raise RuntimeError(f"Malformed idr Git hook: {hook}")


def main():
    _, _, shell_hook, config_path, config_file, manifest, template = sys.argv
    root = Path(git("rev-parse", "--show-toplevel"))
    hooks = Path(git("rev-parse", "--path-format=absolute", "--git-common-dir")) / "hooks"
    # Git's absolute path conversion rejects .git/hooks in linked worktrees
    # before we can repair the inherited setting; normalize it lexically.
    effective = Path(os.path.abspath(git("rev-parse", "--git-path", "hooks")))
    candidates = [p for p in hooks.glob("*") if p.is_file() and not p.is_symlink() and "." not in p.name]
    # Respect a user-selected hook directory (including /dev/null).
    if effective != hooks:
        # Upstream records .git/hooks in the main checkout. A linked worktree
        # inherits that setting but has a .git file, so use the common hooks
        # directory for our launchers and upstream hooks awaiting an upgrade.
        configured = subprocess.run(
            [sys.argv[1], "config", "--get", "core.hooksPath"], capture_output=True, text=True
        ).stdout.strip()
        managed_markers = (MARKER, "# File generated by pre-commit", "# File generated by prek")
        if configured != ".git/hooks" or not any(
            marker in p.read_text(errors="replace") for p in candidates for marker in managed_markers
        ):
            return
        git("config", "--local", "core.hooksPath", str(hooks))
    config = root / config_path
    reinstall = (
        not config.is_symlink()
        or os.readlink(config) != config_file
        or os.environ.get("IDR_GIT_HOOK_REPAIR") == "1"
    )
    if reinstall:
        # Upstream must see its own native hooks when uninstalling/reinstalling,
        # otherwise it can move our launcher to .legacy and recursively run it.
        for hook in candidates:
            native = managed_payload(hook, hook.read_text(errors="replace"))
            if native is not None:
                if native.exists():
                    publish(hook, native.read_text())
                else:
                    hook.unlink()
        if os.environ.get("IDR_GIT_HOOK_REPAIR") == "1" and config.is_symlink():
            config.unlink()
    subprocess.run([shell_hook], check=True)
    # A regular user-owned configuration makes upstream decline installation.
    if not config.is_symlink() or os.readlink(config) != config_file:
        return
    template_text = Path(template).read_text()
    closure = Path(manifest).read_text().rstrip("\n")
    for hook in hooks.glob("*"):
        if not hook.is_file() or hook.is_symlink() or "." in hook.name:
            continue
        content = hook.read_text(errors="replace")
        native = managed_payload(hook, content)
        if native is not None:
            content = native.read_text()
        elif not any(f"# File generated by {tool}" in content for tool in ("pre-commit", "prek")):
            continue
        name = hook.name + ".idr-" + hashlib.sha256(content.encode()).hexdigest()[:20]
        publish(hooks / name, content)
        launcher = template_text
        for key, value in {
            "payload": name,
            "platform": shlex.quote(platform.system() + " " + platform.machine()),
            "config": shlex.quote(config_path),
            "closure": closure,
        }.items():
            launcher = launcher.replace("@" + key + "@", value)
        # Keep upstream's ownership identifiers visible for explicit install or
        # uninstall commands too, without coupling to a particular tool version.
        launcher += "\n" + "\n".join("# " + line for line in content.splitlines()) + "\n"
        publish(hook, launcher)


if __name__ == "__main__":
    main()
